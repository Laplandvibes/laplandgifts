/** Kortin nimi lukijan kielellä. Puuttuva rivi kaatuu testissä, ei tuotannossa. */
export function experienceName(e: GiftExperience, lang: Lang): string {
  if (lang === 'fi') return e.name.fi
  if (lang === 'en') return e.name.en
  return EXPERIENCE_NAMES[lang][e.image] ?? e.name.en
}

/** Paikkakunta lukijan kielellä (picks.ts:n PLACE_NAMES: ja katakana, ko hangul, zh). */
export function experiencePlace(e: GiftExperience, lang: Lang): string {
  if (lang === 'en') return e.place
  return PLACE_NAMES[e.place]?.[lang as GygLocale] ?? e.place
}

/** Kesto lukijan kielen desimaalilla, välimerkillä ja yksiköllä, tai undefined. */
export function experienceDuration(e: GiftExperience, lang: Lang): string | undefined {
  return gygDuration(e, lang)
}
